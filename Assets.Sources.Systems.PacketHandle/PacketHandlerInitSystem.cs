	private void AddTcpHandler<T>(IPacketHandler<T> sub)
	{
		_context.battleServer.Server.RegisterTcpHandler(sub.MethodId(), sub.Handle, sub.Parser);
	}

	private void AddUdpHandler<T>(IPacketHandler<T> sub)
	{
		_context.battleServer.Server.RegisterUdpHandler(sub.MethodId(), sub.Handle, sub.Parser);
	}
