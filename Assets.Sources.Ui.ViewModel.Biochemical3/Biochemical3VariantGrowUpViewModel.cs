{
	private GameObject _oShow;

	private GameObject _oLevel;

	private Text _oLevelText;

	private GameObject _oAddHp;

	private Text _oAddHpText;

	private GameObject _viewGameObject;

	private bool _refrencelessLoaded;

	private string _resourceBundleName = "uiprefabs/biochemical3";

	private string _resourceAssetName = "Biochemical3VariantGrowUp";

	public GameObject ViewGameObject => _viewGameObject;

	public bool ViewGameObjectShow
	{
		get
		{
			if (_viewGameObject != null)
			{
				return _viewGameObject.IsActiveSelf();
			}
			return false;
		}
		set
		{
			if (ViewGameObjectShow != value && _viewGameObject != null)
			{
				_viewGameObject.SetObjectActive(value);
			}
		}
	}

	public bool ShowShow
	{
		get
		{
			if (_oShow != null)
			{
				return _oShow.IsActiveSelf();
			}
			return false;
		}
		set
		{
			if (ShowShow != value && _oShow != null)
			{
				_oShow.SetObjectActive(value);
			}
		}
	}

	public string LevelString
	{
		get
		{
			if (_oLevelText != null)
			{
				return _oLevelText.text;
			}
			return null;
		}
		set
		{
			if (LevelString != value && _oLevelText != null)
			{
				_oLevelText.text = value;
			}
