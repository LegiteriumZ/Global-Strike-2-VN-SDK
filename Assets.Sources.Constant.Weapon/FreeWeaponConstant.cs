	public static string GetWeaponNameByTeam(string weaponName, int team)
	{
		if ("ak47_legend" == weaponName || "rpk_legend" == weaponName)
		{
			switch (team)
			{
			case 1:
				return weaponName + "_t";
			case 2:
				return weaponName + "_ct";
			}
		}
		if ("wolf_mars" == weaponName)
		{
			return "qbz95_wolf";
		}
		return weaponName;
	}

	public static bool IsCombinationWeapon(string masterWeaponName, string otherWeaponName)
	{
		if ((masterWeaponName.Equals("photon_grenade_combination") || masterWeaponName.Equals("photon_grenade_combination1")) && (otherWeaponName.Equals("photon_grenade") || otherWeaponName.Equals("photon_grenade1")))
		{
			return true;
		}
		if ((masterWeaponName.Equals("photon_sword_combination") || masterWeaponName.Equals("photon_sword_combination1")) && (otherWeaponName.Equals("photon_sword") || otherWeaponName.Equals("photon_sword1")))
		{
			return true;
		}
		if ((masterWeaponName.Equals("photon_pistol_combination") || masterWeaponName.Equals("photon_pistol_combination1")) && (otherWeaponName.Equals("photon_pistol") || otherWeaponName.Equals("photon_pistol1")))
		{
			return true;
		}
		return false;
	}

	public static bool IsDoubleRifle(string weaponName)
	{
		if (!weaponName.Contains("double"))
		{
			return weaponName.Contains("mech_dou_akm");
		}
		return true;
	}
